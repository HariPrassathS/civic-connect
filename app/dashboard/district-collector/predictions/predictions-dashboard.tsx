"use client";

import { useMemo } from "react";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { AlertTriangle, MapPin, TrendingUp, ShieldAlert, Activity } from "lucide-react";
import dynamic from "next/dynamic";

const Heatmap = dynamic(() => import("./heatmap"), {
  ssr: false,
  loading: () => <div className="h-[400px] w-full animate-pulse rounded-xl bg-muted" />,
});

export function PredictionsDashboard({ complaints, alerts }: { complaints: any[], alerts: any[] }) {
  
  const getSeverityColor = (severity: string) => {
    switch(severity) {
      case 'critical': return 'bg-red-500/10 text-red-500 border-red-500/20';
      case 'high': return 'bg-orange-500/10 text-orange-500 border-orange-500/20';
      case 'medium': return 'bg-yellow-500/10 text-yellow-500 border-yellow-500/20';
      default: return 'bg-blue-500/10 text-blue-500 border-blue-500/20';
    }
  };

  return (
    <div className="grid gap-6 md:grid-cols-3">
      
      {/* Left Column: Heatmap & Stats */}
      <div className="md:col-span-2 space-y-6">
        <Card>
          <CardHeader>
            <CardTitle>Complaint Density Heatmap</CardTitle>
            <CardDescription>Visualizing hotspots from the last 30 days to identify failing infrastructure.</CardDescription>
          </CardHeader>
          <CardContent>
            <div className="h-[500px] w-full overflow-hidden rounded-xl border">
              <Heatmap data={complaints} />
            </div>
          </CardContent>
        </Card>
      </div>

      {/* Right Column: AI Predictions */}
      <div className="space-y-6">
        <Card className="h-full">
          <CardHeader>
            <CardTitle className="flex items-center gap-2">
              <Activity className="h-5 w-5 text-primary" />
              AI Preventive Alerts
            </CardTitle>
            <CardDescription>Automated insights generated by Groq AI.</CardDescription>
          </CardHeader>
          <CardContent className="space-y-4">
            {alerts.length === 0 ? (
              <div className="flex h-32 flex-col items-center justify-center rounded-lg border border-dashed text-center text-sm text-muted-foreground">
                <ShieldAlert className="mb-2 h-6 w-6 opacity-20" />
                No critical patterns detected.
              </div>
            ) : (
              alerts.map((alert: any) => (
                <div key={alert.id} className="relative overflow-hidden rounded-lg border bg-card p-4 shadow-sm transition-all hover:shadow-md">
                  <div className="mb-2 flex items-start justify-between gap-2">
                    <Badge variant="outline" className={getSeverityColor(alert.severity)}>
                      {alert.severity.toUpperCase()} RISK
                    </Badge>
                    <span className="text-xs font-semibold text-muted-foreground">
                      {alert.confidence_score}% Confidence
                    </span>
                  </div>
                  <h4 className="mb-1 font-semibold leading-tight">{alert.title}</h4>
                  <p className="mb-3 text-xs text-muted-foreground line-clamp-3">
                    {alert.description}
                  </p>
                  
                  <div className="mb-3 flex flex-wrap gap-2 text-xs text-muted-foreground">
                    <div className="flex items-center gap-1">
                      <MapPin className="h-3 w-3" />
                      {alert.ward?.name || 'Unknown Ward'}
                    </div>
                    {alert.category && (
                      <div className="flex items-center gap-1">
                        <TrendingUp className="h-3 w-3" />
                        {alert.category.name}
                      </div>
                    )}
                  </div>

                  <div className="rounded-md bg-primary/5 p-3 text-xs">
                    <span className="block font-semibold text-primary mb-1">Recommended Action:</span>
                    {alert.recommended_action}
                  </div>
                </div>
              ))
            )}
          </CardContent>
        </Card>
      </div>

    </div>
  );
}
